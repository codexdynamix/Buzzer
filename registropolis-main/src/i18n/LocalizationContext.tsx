const normalizedTranslations = Object.fromEntries(
  SUPPORTED_LANGUAGES.map(({ code }) => [
    code,
    Object.fromEntries(
      Object.entries({
        ...translations[code],
        ...screenTranslations[code],
        ...landingTranslations[code],
        ...pageTranslations[code],
        ...componentTranslations[code],
      }).map(([key, value]) => [key.toLocaleLowerCase(), value]),
    ),
  ]),
) as Record<LanguageCode, TranslationCatalog>;

interface LocalizationContextValue {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (source: string) => string;
}

const LocalizationContext = createContext<LocalizationContextValue>({
  language: 'en',
  setLanguage: () => {},
  t: source => source,
});

export const LocalizationProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    const saved = localStorage.getItem('buzzer-language');
    return SUPPORTED_LANGUAGES.some(item => item.code === saved) ? saved as LanguageCode : 'en';
  });

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    localStorage.setItem('buzzer-language', language);
  }, [language]);

  const value = useMemo<LocalizationContextValue>(() => ({
    language,
    setLanguage: setLanguageState,
    t: source => translations[language][source]
      ?? screenTranslations[language]?.[source]
      ?? landingTranslations[language]?.[source]
      ?? pageTranslations[language]?.[source]
      ?? componentTranslations[language]?.[source]
      ?? normalizedTranslations[language][source.toLocaleLowerCase()]
      ?? source,
  }), [language]);

  return <LocalizationContext.Provider value={value}>{children}</LocalizationContext.Provider>;
};

export function useLocalization() {
  return useContext(LocalizationContext);
}
